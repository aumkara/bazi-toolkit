def _fmt_hm(off):
    """±Ч:ММ для дробного оффсета (2.02 → '+2:01')."""
    tot = round(abs(off) * 60)
    return f"{'+' if off >= 0 else '-'}{tot // 60}:{tot % 60:02d}"


