"""validate_synthesis.py — детерминированная проверка чистоты языка СИНТЕЗА (4_synthesis.md; работает и на старых 7_synthesis.md).

Скилл /profile3 (Шаг 4): синтез читает человек, не знающий НИ ОДНОЙ из систем. Поэтому
в нём ЗАПРЕЩЕНЫ: иероглифы; системные НОМЕРА-адреса (ворота/дома/линии/профиль/градусы/% силы);
СПЕЦТЕРМИНЫ систем (Лагна, накшатра, даша, аркан, Меуа, Проектор, Сакрал… — даже русскими буквами).
Раньше чистота держалась только на глазе агента (в одном прогоне «столп» просочился дважды). Линтер
ловит протечки детерминированно. Термины ищутся по границе слова (\b…), чтобы не цеплять «страшила».

ЧЕСТНАЯ ОГОВОРКА (ревью 2026-07-15): гейт ЛЕКСИЧЕСКИЙ и НЕПОЛОН — словарь конечен, перифразы
и смысловые протечки он не видит. Зелёный = «задокументированных протечек нет», НЕ сертификат
чистоты; смысловую чистоту проверяет спот-чек Шага 4.2. HARD-хиты чинить точечными Edit по
выводу линтера (не перегенерацией синтеза), лимит 1–2 итерации.

Использование:
    python3 validate_synthesis.py путь/к/4_synthesis.md              # синтез /profile3 (и старые 7_synthesis.md)
    python3 validate_synthesis.py --compat путь/к/совместимость.md   # /profile3-compare, Шаг 5.5
    python3 validate_synthesis.py --test                             # самопроверка линтера
Выход: 0 — нет HARD-нарушений (SOFT печатаются как предупреждения для ручной проверки);
       1 — есть HARD-нарушение (иероглиф / номер / явный термин) либо файл не читается.
Разрешено и НЕ ловится: год (2026, «с 2026 годом»), возраст/диапазоны (~05:18, 13–16 минут),
разговорное «не/на 100%», «генератор идей» (обычная речь, не тип ДЧ), маркеры
[факт]/[интерпретация]/[спекуляция], названия систем/планет/стихий/знаков/животных года.

--compat добавляет поверх базового словаря жаргон СОВМЕСТИМОСТИ (словарь перенесён из бывшего
grep-блока скилла /profile3-compare (тогда /profile6-compare) — тот зависел от ugrep -P и не имел exit-кода): куты по именам,
Мангал/доша, дришти/дустхана/аспектирует, синастрия/наложение, ретро/комбуст/сожжённый, управитель,
ворота/каналы/авторитет — плюс ЛЮБЫЕ баллы N/N (11.5/36); в compat-режиме и «не 100%»
ловится — перепиши словами.
"""
import re
import sys

CJK = re.compile(r'[㐀-鿿豈-﫿]')

# HARD: однозначный жаргон систем — нарушение, exit 1. Ищется по началу слова (\bTERM, суффикс ок).
HARD_TERMS = [
    # Джйотиш
    "лагна", "накшатр", "граха", "раши", "раху", "кету",
    "варготтам", "кендр", "аянамш", "навамш", "йогакарак", "вимшоттари",
    "асцендент", "сидерическ",   # ветка «Западный взгляд» (2026-07-11): в синтезе — только смыслом
    "шукра", "мангала", "чандра", "сурья", "будха", "шани",      # санскр. планеты
    "гаджакесари", "чандра-мангала",                              # йоги по именам
    "бхукти", "атмакарак",                                        # протечки ревью 2026-07-15
    # Дизайн Человека / Генные Ключи
    "проектор", "генератор", "манифестор", "рефлектор", "сакрал", "селезён",
    # «сакрал» (не «сакральн»): ловит и существительное «отклик сакрала» (пропуск ревью 2026-07-18);
    # «сакраментальный» не цепляет (\bсакрал ≠ сакрам…)
    "аджна", "g-центр", "инкарнацион", "бодиграф", "не-я",
    "сиддх", "гексаграмм",
    # Джунгци
    "меуа", "срог", "вангтанг", "лунгта", "паркха", "лосар",
    # Ба Цзы (однозначные)
    "семь убийств", "клинок овцы", "странствующий конь", "бог пищи",
    "ранящий чиновник", "прямое богатство", "косвенное богатство",
    "косвенная печать", "прямая печать", "立春",
    "я-господин", "личун",                                        # протечки ревью 2026-07-15 («личун» — основа: Личунь/Личуня)
    # Таро/Матрица
    "аркан", "иерофант", "колесо фортуны", "колесница",
]
# SOFT: и термин, и обычное слово (экзальтация/падение/звезда/столп, имя Даша) — предупреждаем, не валим.
# «сплетени» = бывший HARD «солнечное сплетение» (2026-07-15): в простом языке это анатомия
# (легитимна в описании эмоционального авторитета), а не только имя центра ДЧ; основа
# ловит все падежи («солнечного сплетения») и «сплетение обстоятельств» — на глаз.
SOFT_TERMS = ["столп", "отшельник", "император", "жрица", "влюблённые", "звезда",
              "экзальтац", "падени", "гуру", "даш",
              "тропическ", "касп",  # ветка «Западный взгляд»: и термин, и быт (тропический климат, Каспий)
              "сплетени",
              "авторитет"]  # и термин ДЧ, и обычная речь («он авторитет в теме»); однозначные
                            # коллокации ДЧ («внутренний авторитет») — HARD ниже (2026-07-18)

# Системные НОМЕРА-адреса. Год/возраст/диапазоны/«не 100%» сюда НЕ попадают.
# «N-й дом»: между числом(+суффиксом) и «дом» ОБЯЗАН быть разделитель — иначе
# «с 2026 годом» ловилось как «го»+«дом» (ложный HARD на обязательном контенте года).
# Зеркальные формы «34-е ворота»/«5-я линия»/«20-й канал» (число ПЕРЕД словом) — пропуск
# ревью 2026-07-18; бытовые омонимы с цифрой редки (пробы в --test), потому HARD.
NUM_PATTERNS = [
    (r'\bворот[аеохуы]*\s+№?\s*\d', "ворота N"),       # \b: «поворот 5» — не ворота
    (r'\d+\s*[-–]?\s*[а-яё]{0,2}[-\s]+ворот\w*\b', "N-е ворота"),   # «по» перед «ворот» не пройдёт: нужен разделитель
    (r'\bключ[аеиу]?\s+№?\s*\d', "ключ N"),
    (r'\bканал[аеовуы]*\s+№?\s*\d', "канал N"),
    (r'\d+\s*[-–]?\s*[а-яё]{0,2}[-\s]+канал\w*\b', "N-й канал"),
    (r'\bлини[яиюейё]\s+\d', "линия N"),
    (r'\d+\s*[-–]?\s*[а-яё]{0,2}[-\s]+лини[яиюейё]\w*\b', "N-я линия"),
    (r'\bпад[аеыу]?\s+\d', "пада N"),
    (r'(?<!\d)\d\s*/\s*\d(?!\d)', "N/N (профиль?)"),
    (r'\d+[.,]\d+\s*°|\d+\s*°', "градусы"),
    (r'\d+(?:[.,]\d+)?\s*%', "% (сила/вес)"),           # и целые проценты: «37%» — тоже адрес
    (r'тен[ьи]\s*(?:→|->)\s*дар', "Тень→Дар (спектр ГК)"),
    (r'\b(?:внутренн|эмоциональн|сакральн|селезёночн|лунн|эго)\w*[-\s]+авторитет', "авторитет ДЧ"),
]

# SOFT-номера (сплит 2026-07-18): «дом» с номером — и жаргон (астрологические дома), и бытовой
# русский («дом 5 по улице», «второй дом купили»). Ложный HARD наказывал простой язык —
# инверсия цели гейта. Теперь предупреждение: человек смотрит глазами, гейт не валится.
SOFT_NUM_PATTERNS = [
    (r'\bдом[аеуов]*\s+№?\s*\d', "дом N (жаргон или адрес?)"),
    (r'\d+\s*[-–]?\s*(?:й|го|м|е|ом|ой)?[-\s]+дом\b', "N-й дом (жаргон или быт?)"),
    (r'\b(?:перв|втор|трет|четв[её]рт|пят|шест|седьм|восьм|девят|десят|одиннадцат|двенадцат)\w*'
     r'\s+дом(?:ом|а|е|у)?\b',
     "дом словами (жаргон или быт?)"),   # только формы существительного «дом» — «второй домашний…» не цепляет
]

# Разрешённые обороты: совпадение внутри них НЕ считается нарушением.
ALLOW_PATTERNS = [
    r'\bгенератор\w*\s+иде[йи]\w*',      # «генератор идей» — обычная речь, не тип ДЧ
]
ALLOW_PATTERNS_NONCOMPAT = [
    r'\b(?:не|на)\s+100\s*%',            # разговорное «не/на 100%»; в compat-режиме НЕ разрешено
]

# ── --compat: жаргон СОВМЕСТИМОСТИ (/profile3-compare) поверх базового словаря ──
# Полные формы с границами (\b…\b), чтобы «кут» не цеплял «кутёж», «дош» — «дошёл»,
# «ворота» — «поворот». Однословный ярлык = что это за термин (для сообщения).
COMPAT_HARD_PATTERNS = [
    (r'\bкут[аыеу]?\b', "кута"),
    (r'\bаштакут\w*', "Аштакута"),
    (r'\bмангал\w*', "Мангал"),
    (r'\bдош[аиеу]\b', "доша"),
    (r'\bнади\b', "Нади"),
    (r'\bйони\b', "Йони"),
    (r'\bбхакут\w*', "Бхакут"),
    (r'\bвашь[яию]\w*', "Вашья"),
    (r'\bварн[аыеу]\b', "Варна"),
    (r'\bсинастри\w*', "синастрия"),
    (r'\bдришт\w*', "дришти"),
    (r'\bдустхан\w*', "дустхана"),
    (r'\bаспектир\w*', "аспектирует"),
    (r'\bкомбуст\w*', "комбуст"),
    (r'\bретроградн\w*', "ретроградный"),
    (r'\bсожж\w*', "сожжённый"),
    (r'\bуправител\w*', "управитель"),
    (r'\bналожени\w*', "наложение домов"),
    (r'\bворот[аы]\b', "ворота"),
    (r'\bканалы\b', "каналы"),
    (r'\bавторитет\w*', "авторитет"),
    (r'\bэлектромагнит\w*', "электромагнетика"),
    (r'\bседьм\w*\s+дом\w*|\bдом\w*\s+седьм\w*', "седьмой дом"),
]
COMPAT_NUM_PATTERNS = [
    (r'\d+(?:[.,]\d+)?\s*/\s*\d+', "баллы N/N"),
]
# Двусмысленные слова совместимости: и калька ярлыков движка, и обычная речь.
COMPAT_SOFT_TERMS = ["седьм", "компромисс", "доминирован"]


def _allowed_spans(low, compat):
    pats = ALLOW_PATTERNS + ([] if compat else ALLOW_PATTERNS_NONCOMPAT)
    return [m.span() for p in pats for m in re.finditer(p, low)]


def _term_hits(low, terms, allow):
    """Совпадения терминов по началу слова (\bTERM, суффикс допускается), вне allow-спанов."""
    hits = []
    for t in terms:
        for m in re.finditer(r'\b' + re.escape(t), low):
            if not _inside(m.span(), allow):
                hits.append(t)
                break
    return hits


def _inside(span, allow):
    return any(span[0] >= a and span[1] <= b for a, b in allow)


def scan_lines(lines, compat=False):
    """Ядро проверки: (hard, soft) по списку строк. Вынесено из scan() ради --test."""
    num_patterns = NUM_PATTERNS + (COMPAT_NUM_PATTERNS if compat else [])
    soft_terms = SOFT_TERMS + (COMPAT_SOFT_TERMS if compat else [])
    hard, soft = [], []
    for i, line in enumerate(lines, 1):
        low = line.lower()
        allow = _allowed_spans(low, compat)
        for m in CJK.finditer(line):
            hard.append((i, "иероглиф", m.group()))
        for pat, label in num_patterns:
            for m in re.finditer(pat, low):
                if not _inside(m.span(), allow):
                    hard.append((i, label, m.group().strip()))
        for pat, label in SOFT_NUM_PATTERNS:
            for m in re.finditer(pat, low):
                if not _inside(m.span(), allow):
                    soft.append((i, label, m.group().strip()))
        for t in _term_hits(low, HARD_TERMS, allow):
            hard.append((i, "термин", t))
        if compat:
            for pat, label in COMPAT_HARD_PATTERNS:
                for m in re.finditer(pat, low):
                    if not _inside(m.span(), allow):
                        hard.append((i, f"термин: {label}", m.group().strip()))
        for t in _term_hits(low, soft_terms, allow):
            soft.append((i, "слово(?)", t))
    return hard, soft


def scan(path, compat=False):
    try:
        lines = open(path, encoding="utf-8").read().splitlines()
    except OSError as e:
        print(f"FAIL: не читается {path}: {e}")
        return None
    return scan_lines(lines, compat=compat)


def _test():
    """Самопроверка: задокументированные ложные HARD (ревью 2026-07-15/18) зелёные, протечки красные,
    бытовой «дом» и двусмысленности — SOFT (не валят гейт), household-батарея — зелёная."""
    ok = True
    green_base = [
        "Работа с 2026 годом требует терпения.",       # ловилось как «го»+«дом»
        "За 2026 годом придёт следующий.",
        "Он генератор идей и человек дела.",           # не тип ДЧ
        "Поворот 5 закрыл сезон.",                     # не «ворота 5»
        "Уверен не на 100%.", "Он не 100% уверен.",    # разговорное
        "Волну лучше прожить телом, в области солнечного сплетения.",  # анатомия → SOFT, не HARD
        "Дата рождения 1990-03-03, окно 33–43 лет.",
        # ── household-батарея 2026-07-18: бытовой русский НЕ должен давать HARD ──
        "Второй дом купили под дачу.",                 # был ложный HARD «дом словами»
        "Дом 5 по улице Садовой.",                     # был ложный HARD «дом N»
        "Вышли через ворота стадиона.",                # «ворота» без числа — не адрес
        "Переплыл канал за час, на 5-м повороте устал.",  # «канал» без числа; «поворот» не ворота
        "Линия поведения выбрана давно.",              # «линия» без числа
        "Он авторитет для коллег.",                    # бытовой «авторитет» → SOFT, не HARD
        "Прозвучала сакраментальная фраза.",           # не «сакрал»
    ]
    red_base = [
        "Ворота 34 дают напор.", "Канал 34-20 определяет темп.",
        "34-е ворота дают напор.", "20-й канал задаёт темп.",   # зеркальные формы (пропуск 07-18)
        "5-я линия делает наставником.", "Линия 2 — отшельник.",
        "Отклик сакрала — главный компас.",                     # существительное «сакрал» (пропуск 07-18)
        "Внутренний авторитет — эмоциональный.",                # однозначная коллокация ДЧ
        "Гексаграмма 5 в основе.", "Путь Тень → Дар открыт.",
        "Сила воды 37%.", "Я-господин — слабая вода.",
        "После Личуня год сменился.",
        "Лагна во Льве.", "立春 пришёл.", "Профиль 3/5.",
        "Дают о себе знать бхукти и атмакарака.",
    ]
    # бытовой/жаргонный «дом» после сплита: НЕ HARD, но виден как SOFT (человек смотрит глазами)
    soft_expected = [
        "Седьмой дом отвечает за партнёрство.",
        "7-й дом активен.",
        "Он авторитет для коллег.",
    ]
    for text in green_base:
        hard, _ = scan_lines([text])
        if hard:
            ok = False
            print(f"[FAIL] ложный HARD: «{text}» → {hard}")
    for text in red_base:
        hard, _ = scan_lines([text])
        if not hard:
            ok = False
            print(f"[FAIL] протечка не поймана: «{text}»")
    for text in soft_expected:
        hard, soft = scan_lines([text])
        if hard or not soft:
            ok = False
            print(f"[FAIL] ожидался SOFT (и только SOFT): «{text}» → hard={hard}, soft={soft}")
    # compat: «не 100%» и баллы ловятся, «дошёл»/«кутёж»/«поворот» — нет
    ch, _ = scan_lines(["Совпадение не 100%, счёт 11.5/36."], compat=True)
    if len(ch) < 2:
        ok = False
        print(f"[FAIL] compat: «не 100%»/баллы не пойманы → {ch}")
    ch2, _ = scan_lines(["Он дошёл до кутежа за поворотом."], compat=True)
    if ch2:
        ok = False
        print(f"[FAIL] compat: ложный HARD на быту → {ch2}")
    print(f"validate_synthesis --test: {'ЗЕЛЁНО ✓' if ok else 'КРАСНОЕ ✗'} "
          f"({len(green_base)} разрешённых + {len(red_base)} протечек + {len(soft_expected)} SOFT + 2 compat)")
    return ok


def main():
    args = sys.argv[1:]
    if "--test" in args:
        return 0 if _test() else 1
    compat = "--compat" in args
    paths = [a for a in args if not a.startswith("--")]
    if not paths:
        print("Использование: validate_synthesis.py [--compat] путь/к/файлу.md | --test", file=sys.stderr)
        return 2
    path = paths[0]
    res = scan(path, compat=compat)
    if res is None:
        return 1
    hard, soft = res
    print(f"validate_synthesis{' [compat]' if compat else ''}: {path}")
    print("─" * 60)
    if soft:
        print(f"SOFT (проверь вручную — двусмысленные слова), {len(soft)}:")
        for ln, kind, tok in soft:
            print(f"  ~ строка {ln}: [{kind}] «{tok}»")
    if hard:
        print(f"HARD (нарушения — переписать), {len(hard)}:")
        for ln, kind, tok in hard:
            print(f"  ✗ строка {ln}: [{kind}] «{tok}»")
        print("─" * 60)
        print(f"ИТОГ: КРАСНОЕ ✗ — {len(hard)} HARD-нарушений (синтез не чист). "
              f"Чинить точечными Edit по строкам выше, лимит 1–2 итерации.")
        return 1
    print("─" * 60)
    print("ИТОГ: ЗЕЛЁНО ✓ — задокументированных протечек нет"
          + (f"; {len(soft)} SOFT на ручную проверку" if soft else "")
          + ". (Гейт лексический и неполон: зелёный ≠ сертификат чистоты — смысл проверяет спот-чек 4.2.)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
