def _sexagenary(year):
    """(животное, стихия) для года по 60-летнему циклу (после Лосара)."""
    branch = (year - 4) % 12
    stem = (year - 4) % 10
    return ANIMALS[branch], ELEMENTS[stem // 2]


def birth_mewa(year):
    """Меуа года (1-9). Якорь 1927=1, счёт назад по циклу 9. ВНИМАНИЕ: год —
    лунный (рождения до Лосара относятся к предыдущему году)."""
    val = (1 - (year - MEWA_ANCHOR_YEAR)) % 9
    return val if val != 0 else 9


