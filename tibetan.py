def _forces_year(forces, forecast_year):
    """Отношение каждой ВЫЧИСЛЕННОЙ силы к стихии прогнозного года."""
    yanimal, yelem = _sexagenary(forecast_year)
    out = {"year": forecast_year, "year_sign": f"{yelem} {yanimal}", "year_element": yelem, "relations": {}}
    for name, data in forces.items():
        if not data.get("element"):
            continue
        rel, reading = _relation(_eidx(data["element"]), _eidx(yelem))
        out["relations"][name] = {"force_element": data["element"], "relation": rel, "reading": reading}
    return out


def _lichun_date(year):
    """UTC-дата Личуня (立春, ~4 фев) календарного года — Swiss Ephemeris через jieqi.py.
    None, если эфемериды недоступны: честный отказ, приближений не делаем (политика проекта).
    Нужна только для флага расхождения календарей с Ба Цзы — сам тибетский расчёт от неё не зависит."""
    try:
        from jieqi import find_solar_term, jd_to_datetime
        return jd_to_datetime(find_solar_term(year, 315)).date()
    except Exception:
        return None


def resolve_forecast_year(as_of):
    """Тибетский год, действующий на дату as_of: граница года — ЛОСАР, не 1 января.
    Возвращает (год, словарь-обоснование для JSON). Окно 1 янв → Лосар (~5–9 недель)
    без этого резолва ежегодно получало неверный прогнозный год."""
    y = as_of.year
    ld = losar_date(y)
    boundary = {"as_of": as_of.isoformat(), "losar": ld.isoformat() if ld else None,
                "rule": "граница тибетского года — Лосар (Пхугпа), не 1 января"}
    if ld is None:
        boundary["basis"] = (f"год {y} вне таблицы Лосаров (1900–2100) — взят календарный год" +
                             ("; в янв–марте фактический тибетский год может быть предыдущим"
                              if as_of.month <= 3 else ""))
        return y, boundary
    if as_of < ld:
        boundary["basis"] = f"дата до Лосара {ld.isoformat()} → тибетский год ещё {y - 1}"
        return y - 1, boundary
    boundary["basis"] = ("сам день Лосара — год уже сменился (тибетские сутки начинаются на рассвете)"
                         if as_of == ld else f"дата после Лосара {ld.isoformat()} → тибетский год {y}")
    return y, boundary


def _divergence_with_bazi(d, tibetan_year):
    """Флаг окна, где годы Джунгци и Ба Цзы законно РАСХОДЯТСЯ (границы: Лосар vs Личунь).
    Двунаправленно: обычное окно Личунь→Лосар и зеркальное Лосар→Личунь (Лосар раньше Личуня,
    напр. 1916: Лосар 02-04 < Личунь ~02-05). None = вне окна / нет таблицы / нет эфемерид."""
    losar_d = losar_date(d.year)
    lichun_d = _lichun_date(d.year)
    if losar_d is None or lichun_d is None or losar_d == lichun_d:
        return None
    lo, hi = sorted([lichun_d, losar_d])
    if not (lo <= d < hi):
        return None
    bazi_year = d.year if d >= lichun_d else d.year - 1   # по дате; в сам день Личуня решает час/пояс
    if bazi_year == tibetan_year:
        return None
    ba, be = _sexagenary(bazi_year)
    out = {
        "window": ("Личунь→Лосар: год Ба Цзы уже сменился, тибетский ещё прежний"
                   if lichun_d < losar_d else
                   "Лосар→Личунь (зеркальное окно): тибетский год уже сменился, год Ба Цзы ещё прежний"),
        "lichun": lichun_d.isoformat(), "losar": losar_d.isoformat(),
        "bazi_year": bazi_year, "bazi_year_sign": f"{be} {ba}",
        "tibetan_year": tibetan_year,
        "note": "Дата между границами двух календарей: знаки года Ба Цзы и Джунгци законно "
                "РАЗНЫЕ — это два календаря (Личунь vs Лосар), не ошибка расчёта.",
    }
    if d == lichun_d:
        out["note"] += (" Это сам день Личуня: принадлежность года Ба Цзы зависит от часа и "
                        "пояса — решает bazi.py.")
    return out


