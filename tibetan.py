def _eidx(name):
    return ELEMENTS.index(name)


def _relation(force_idx, other_idx):
    """Отношение стихии `other` (напр. года) К стихии силы `force_idx`.
    Цикл ELEMENTS = продуктивный (生). Конвенция друг/враг — по Берзину."""
    if other_idx == force_idx:
        return ("тождество", "год той же стихии — сила устойчива, подкреплена")
    if other_idx == (force_idx - 1) % 5:               # other ПОРОЖДАЕТ force
        return ("мать", "год питает эту силу — поддержка, рост")
    if other_idx == (force_idx + 1) % 5:               # force ПОРОЖДАЕТ other
        return ("ребёнок", "сила отдаёт энергию году — расход, истощение, береги её")
    if other_idx == (force_idx + 2) % 5:               # force КОНТРОЛИРУЕТ other
        return ("друг", "сила доминирует над годом — активна, но тратится в борьбе")
    if other_idx == (force_idx - 2) % 5:               # other КОНТРОЛИРУЕТ force
        return ("враг", "год давит на эту силу — препятствие, уязвимость")
    return ("?", "")


def _lu(animal, year_elem):
    """Лю (тело), двухшаговое правило (Erlewine 546-547 + astrotibet, сверено 60/60):
    ключ по животному (LU_KEY), затем отношение стихии ГОДА к ключу:
    год=сын ключа → Вода; год=мать → Дерево; год покоряет ключ (враг) → Земля;
    ключ покоряет год (друг) → Огонь; та же стихия → Металл."""
    ki, yi = _eidx(LU_KEY[animal]), _eidx(year_elem)
    if yi == ki:
        return "Железо (Металл)"
    if yi == (ki + 1) % 5:                              # год = сын ключа
        return "Вода"
    if yi == (ki - 1) % 5:                              # год = мать ключа
        return "Дерево"
    if yi == (ki + 2) % 5:                              # ключ покоряет год (друг)
        return "Огонь"
    return "Земля"                                      # год покоряет ключ (враг)


def _obstacle_year(birth_animal, forecast_year):
    """Год препятствий для прогнозного года. ЛО-СКАГ = возврат знака рождения
    (каждые 12 лет) — ВЫВЕРЕНО (Берзин + Эрлевайн + Бон, 2026-07-11).
    ДУН-ЗУР = противоположный знак — правило из 2 источников, термин из одного.
    Прочие «тёмные» годы — 1 источник, не выдаём (см. not_computed)."""
    fanimal, _ = _sexagenary(forecast_year)
    diff = (ANIMALS.index(fanimal) - ANIMALS.index(birth_animal)) % 12
    if diff == 0:
        return {"type": "ло-скаг (год возврата знака)", "confidence": "высокая",
                "reading": "традиционный «год препятствий»: беречь здоровье и ресурсы, "
                           "не форсировать большие начинания"}
    if diff == 6:
        return {"type": "дун-зур (противоположный знак)",
                "confidence": "средняя — правило подтверждают 2 источника, термин один",
                "reading": "второй по значимости год осторожности после ло-скаг"}
    return None


